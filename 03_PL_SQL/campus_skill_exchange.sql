CREATE OR REPLACE PACKAGE cse_match_pkg AS
    PROCEDURE recommend_for(p_user_id IN NUMBER);
END cse_match_pkg;
/

CREATE OR REPLACE PACKAGE BODY cse_match_pkg AS
    PROCEDURE recommend_for(p_user_id IN NUMBER) IS
        v_found BOOLEAN := FALSE;
    BEGIN
        FOR match_row IN (
            SELECT peer.user_id, peer.full_name,
                   COUNT(DISTINCT CASE WHEN theirs.skill_type = 'TEACH'
                       THEN theirs.skill_id END) AS can_teach_you,
                   COUNT(DISTINCT CASE WHEN theirs.skill_type = 'LEARN'
                       THEN theirs.skill_id END) AS can_learn_from_you
            FROM cse_users me
            JOIN cse_user_skills mine ON mine.user_id = me.user_id
            JOIN cse_user_skills theirs ON theirs.skill_id = mine.skill_id
                AND theirs.user_id <> me.user_id
            JOIN cse_users peer ON peer.user_id = theirs.user_id
            WHERE me.user_id = p_user_id
              AND me.is_active = 1
              AND peer.is_active = 1
              AND ((mine.skill_type = 'LEARN' AND theirs.skill_type = 'TEACH')
                OR (mine.skill_type = 'TEACH' AND theirs.skill_type = 'LEARN'))
            GROUP BY peer.user_id, peer.full_name
            ORDER BY (COUNT(DISTINCT CASE WHEN theirs.skill_type = 'TEACH'
                           THEN theirs.skill_id END)
                    + COUNT(DISTINCT CASE WHEN theirs.skill_type = 'LEARN'
                           THEN theirs.skill_id END)) DESC,
                     peer.full_name
        ) LOOP
            v_found := TRUE;
            DBMS_OUTPUT.PUT_LINE(
                match_row.full_name || ': ' ||
                (CASE WHEN match_row.can_teach_you > 0 THEN 'can teach you; ' END) ||
                (CASE WHEN match_row.can_learn_from_you > 0 THEN 'can learn from you' END)
            );
        END LOOP;
        IF NOT v_found THEN
            DBMS_OUTPUT.PUT_LINE('No complementary skill matches found.');
        END IF;
    END recommend_for;
END cse_match_pkg;
/
