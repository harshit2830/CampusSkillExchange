-- Oracle SQL / PL/SQL schema for Campus Skill Exchange.
-- Run in a new Oracle schema with permission to create tables and packages.

CREATE TABLE cse_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(254) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    college VARCHAR2(150) NOT NULL,
    department VARCHAR2(100) NOT NULL,
    semester NUMBER(2) NOT NULL,
    bio VARCHAR2(500) DEFAULT '',
    role VARCHAR2(10) DEFAULT 'student' NOT NULL
        CONSTRAINT cse_users_role_ck CHECK (role IN ('student', 'admin')),
    is_active NUMBER(1) DEFAULT 1 NOT NULL
        CONSTRAINT cse_users_active_ck CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE cse_skills (
    skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR2(100) NOT NULL UNIQUE,
    category VARCHAR2(80) NOT NULL
);

CREATE TABLE cse_user_skills (
    user_skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    skill_id NUMBER NOT NULL REFERENCES cse_skills(skill_id) ON DELETE CASCADE,
    skill_type VARCHAR2(5) NOT NULL
        CONSTRAINT cse_user_skills_type_ck CHECK (skill_type IN ('TEACH', 'LEARN')),
    proficiency VARCHAR2(12) DEFAULT 'BEGINNER' NOT NULL
        CONSTRAINT cse_user_skills_level_ck
        CHECK (proficiency IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    CONSTRAINT cse_user_skills_uq UNIQUE (user_id, skill_id, skill_type)
);

CREATE TABLE cse_user_preferences (
    preference_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL UNIQUE REFERENCES cse_users(user_id) ON DELETE CASCADE,
    campus_location VARCHAR2(120) DEFAULT '' NOT NULL,
    preferred_format VARCHAR2(12) DEFAULT 'Either' NOT NULL
        CONSTRAINT cse_preferences_format_ck
        CHECK (preferred_format IN ('In person', 'Online', 'Either')),
    languages VARCHAR2(200) DEFAULT '' NOT NULL,
    availability_notes VARCHAR2(500) DEFAULT '' NOT NULL
);

CREATE TABLE cse_availability_slots (
    availability_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    note VARCHAR2(200) DEFAULT '' NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL
        CONSTRAINT cse_availability_active_ck CHECK (is_active IN (0, 1)),
    CONSTRAINT cse_availability_time_ck CHECK (ends_at > starts_at)
);

CREATE TABLE cse_exchange_requests (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    receiver_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    skill_offered_id NUMBER NOT NULL REFERENCES cse_skills(skill_id),
    skill_requested_id NUMBER NOT NULL REFERENCES cse_skills(skill_id),
    message VARCHAR2(500) DEFAULT '',
    status VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
        CONSTRAINT cse_requests_status_ck
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT cse_requests_distinct_users_ck CHECK (sender_id <> receiver_id)
);

CREATE TABLE cse_sessions (
    session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id NUMBER NOT NULL REFERENCES cse_exchange_requests(request_id) ON DELETE CASCADE,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    location VARCHAR2(200) NOT NULL,
    notes VARCHAR2(500) DEFAULT '',
    status VARCHAR2(10) DEFAULT 'SCHEDULED' NOT NULL
        CONSTRAINT cse_sessions_status_ck
        CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT cse_sessions_time_ck CHECK (ends_at > starts_at)
);

CREATE TABLE cse_session_changes (
    change_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id NUMBER NOT NULL REFERENCES cse_sessions(session_id) ON DELETE CASCADE,
    proposer_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    location VARCHAR2(200) NOT NULL,
    status VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
        CONSTRAINT cse_session_change_status_ck
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT cse_session_change_time_ck CHECK (ends_at > starts_at)
);

CREATE TABLE cse_reviews (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id NUMBER NOT NULL REFERENCES cse_sessions(session_id) ON DELETE CASCADE,
    reviewer_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    rating NUMBER(1) NOT NULL CONSTRAINT cse_reviews_rating_ck CHECK (rating BETWEEN 1 AND 5),
    review_text VARCHAR2(1000) DEFAULT '',
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT cse_reviews_once_uq UNIQUE (session_id, reviewer_id)
);

CREATE TABLE cse_notifications (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    message VARCHAR2(500) NOT NULL,
    is_read NUMBER(1) DEFAULT 0 NOT NULL
        CONSTRAINT cse_notifications_read_ck CHECK (is_read IN (0, 1)),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE cse_messages (
    message_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    recipient_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    message_body VARCHAR2(2000) NOT NULL,
    is_read NUMBER(1) DEFAULT 0 NOT NULL
        CONSTRAINT cse_message_read_ck CHECK (is_read IN (0, 1)),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT cse_message_distinct_ck CHECK (sender_id <> recipient_id)
);

CREATE TABLE cse_saved_students (
    saved_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    student_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    CONSTRAINT cse_saved_student_uq UNIQUE (user_id, student_id),
    CONSTRAINT cse_saved_student_self_ck CHECK (user_id <> student_id)
);

CREATE TABLE cse_saved_skills (
    saved_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL REFERENCES cse_users(user_id) ON DELETE CASCADE,
    skill_id NUMBER NOT NULL REFERENCES cse_skills(skill_id) ON DELETE CASCADE,
    CONSTRAINT cse_saved_skill_uq UNIQUE (user_id, skill_id)
);

CREATE TABLE cse_reports (
    report_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    reported_user_id NUMBER NOT NULL REFERENCES cse_users(user_id),
    reason VARCHAR2(500) NOT NULL,
    status VARCHAR2(10) DEFAULT 'OPEN' NOT NULL
        CONSTRAINT cse_reports_status_ck CHECK (status IN ('OPEN', 'REVIEWED', 'DISMISSED')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX cse_user_skills_lookup_idx ON cse_user_skills(skill_id, skill_type);
CREATE INDEX cse_requests_receiver_idx ON cse_exchange_requests(receiver_id, status);
CREATE INDEX cse_notifications_user_idx ON cse_notifications(user_id, is_read);

